#!/usr/bin/env python3
"""Validate the skills repository. Run from anywhere: python3 scripts/validate_skills.py

Checks:
  1. every skills/*/scripts/*.py that offers --self-test passes it, normally and under `python -O`;
  2. every relative Markdown link in README.md and skills/**/*.md resolves, including #anchors;
  3. every skills/*/SKILL.md has YAML frontmatter with `name` (equal to its directory, [a-z0-9-]) and a
     non-empty `description` of at most 1024 characters, written as a one-line YAML scalar (plain, 'single'- or
     "double"-quoted) that parses as the complete intended string: a plain scalar must not contain ": " or " #",
     end with ":", or start with an indicator character (YAML would fail or truncate it). `--self-test` checks
     this parser against fixtures; the full run includes it, normally and under `python -O`;
  4. every skill has agents/openai.yaml with interface.display_name, short_description and a
     default_prompt that names the skill as $<skill-name>;
  5. no absolute user-home paths (/Users/<name>, C:\\Users\\<name>) or project checkout paths leak into the skills;
  6. no vendor model text is embedded in scripts, model files or fenced code (licence markers, or
     .subckt/.model cards larger than a short illustrative example);
  7. the design documents in rfcs/ and the shared operational sources in operational/ get checks 2 and 5 too;
  8. no new relative link from one skill into another: scripts/cross-skill-links.json lists the existing ones, a link
     not listed fails, and a listed link that no longer exists fails too (the list only shrinks);
  9. the generated copies of operational/ sources are in sync (scripts/operational_sync.py, read-only) and every
     example record in operational/examples/ is valid (scripts/operational_records.py); both scripts' --self-test
     runs with the skills' scripts.
Standard library only. Exit status 1 on any failure.
"""

from __future__ import annotations

import importlib.util
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"
RFCS = ROOT / "rfcs"
OPERATIONAL = ROOT / "operational"
LINK_BASELINE = ROOT / "scripts" / "cross-skill-links.json"
REPO_SCRIPTS = [ROOT / "scripts" / "operational_sync.py", ROOT / "scripts" / "operational_records.py"]
PATH_LEAK = re.compile(r"/Users/[A-Za-z]|[A-Za-z]:\\Users\\|yellow-punch/")   # container paths such as /home/build are fine
VENDOR_MARKERS = re.compile(r"all rights reserved|model generated by|pspice model editor|commercial use or resale", re.I)
MODEL_FILES = {".lib", ".mod", ".cir", ".sp", ".spi", ".inc", ".py", ".cpp", ".hpp", ".txt"}
MAX_SUBCKT_LINES, MAX_MODEL_PARAMS = 25, 12


def anchors(path: Path) -> set[str]:
    out = set()
    text = re.sub(r"```.*?```", "", path.read_text(encoding="utf-8"), flags=re.S)
    for line in text.split("\n"):
        m = re.match(r"^#+\s+(.*)", line)
        if m:
            out.add(re.sub(r"[^\w\s-]", "", m.group(1).strip().lower()).replace(" ", "-"))
    return out


def documents() -> list[Path]:
    """Markdown covered by the link and anchor check."""
    return [ROOT / "README.md", *sorted(SKILLS.rglob("*.md")), *sorted(RFCS.rglob("*.md")),
            *sorted(OPERATIONAL.rglob("*.md"))]


def check_links(problems: list[str]) -> int:
    count = 0
    for md in documents():
        text = re.sub(r"```.*?```", "", md.read_text(encoding="utf-8"), flags=re.S)
        for m in re.finditer(r"\]\(([^)\s]+)\)", text):
            link = m.group(1)
            if link.startswith(("http://", "https://", "mailto:")):
                continue
            count += 1
            path, _, anchor = link.partition("#")
            target = (md.parent / path).resolve() if path else md
            if not target.exists():
                problems.append(f"broken link {md.relative_to(ROOT)} -> {link}")
            elif anchor and target.suffix == ".md" and anchor not in anchors(target):
                problems.append(f"broken anchor {md.relative_to(ROOT)} -> {link}")
    return count


DQ_ESCAPES = {"0": "\0", "a": "\a", "b": "\b", "t": "\t", "\t": "\t", "n": "\n", "v": "\v", "f": "\f", "r": "\r", "e": "\x1b",
              " ": " ", '"': '"', "/": "/", "\\": "\\", "N": "\x85", "_": "\xa0", "L": "\u2028", "P": "\u2029"}


def parse_scalar(raw: str) -> tuple[str | None, str | None]:
    """The value of a one-line YAML scalar as YAML would read it, or (None, reason) when it would not parse as the
    complete intended string. Plain, 'single'- and "double"-quoted forms; block (| >) and multi-line scalars are refused."""
    text = raw.strip()
    if not text:
        return None, "empty"
    if text[0] in "|>":
        return None, "block scalars (| or >) are not supported here: write the description on one line"
    if text[0] in "'\"":
        q, i, out = text[0], 1, []
        while i < len(text):
            c = text[i]
            if q == "'" and c == "'":
                if text[i + 1:i + 2] == "'":
                    out.append("'")
                    i += 2
                    continue
                break
            if q == '"' and c == "\\":
                esc = text[i + 1:i + 2]
                if esc in DQ_ESCAPES:
                    out.append(DQ_ESCAPES[esc])
                    i += 2
                    continue
                width = {"x": 2, "u": 4, "U": 8}.get(esc)
                digits = text[i + 2:i + 2 + width] if width else ""
                if not width or not re.fullmatch(r"[0-9A-Fa-f]+", digits) or len(digits) != width:
                    return None, f"invalid escape \\{esc} in a double-quoted scalar"
                out.append(chr(int(digits, 16)))
                i += 2 + width
                continue
            if q == '"' and c == '"':
                break
            out.append(c)
            i += 1
        else:
            return None, f"unterminated {q}-quoted scalar"
        rest = text[i + 1:]
        if rest.strip() and not re.match(r"\s+#", rest):
            return None, f"text after the closing quote: {rest.strip()[:30]!r}"
        return "".join(out), None
    if text[0] in ",[]{}#&*!%@`" or (text[0] in "-?:" and (len(text) == 1 or text[1] == " ")):
        return None, f"a plain scalar cannot start with {text[0]!r}: quote the description"
    if ": " in text or text.endswith(":"):
        return None, "a plain scalar cannot contain ': ' or end with ':' (YAML reads a mapping): quote it or rephrase"
    if " #" in text or "\t#" in text:
        return None, "' #' starts a YAML comment and would truncate a plain scalar: quote it or rephrase"
    return text, None


def frontmatter_description(frontmatter: str) -> tuple[str | None, str | None]:
    lines = frontmatter.split("\n")
    for i, line in enumerate(lines):
        m = re.match(r"^description:(.*)$", line)
        if m:
            if m.group(1).strip()[:1] in ("|", ">"):
                return parse_scalar(m.group(1))   # refused with the block-scalar message
            if i + 1 < len(lines) and lines[i + 1][:1] in (" ", "\t") and lines[i + 1].strip():
                return None, "multi-line description: write it on one line"
            return parse_scalar(m.group(1))
    return None, "missing"


# (frontmatter text, expected description or None, a fragment of the expected error)
DESCRIPTION_FIXTURES = [
    ("name: x\ndescription: Build plugins with CMake, covering lifecycle and state.", "Build plugins with CMake, covering lifecycle and state.", None),
    ("description: Model BBD circuits (MN3xxx) as DSP; use for chorus, flanger.", "Model BBD circuits (MN3xxx) as DSP; use for chorus, flanger.", None),
    ("description: A URL https://example.com/a:b and C:\\path stay plain", "A URL https://example.com/a:b and C:\\path stay plain", None),
    ("description: 'Use it: quoted, with it''s apostrophe'", "Use it: quoted, with it's apostrophe", None),
    ('description: "Use it: quoted, with a \\"quote\\" and C:\\\\path"', 'Use it: quoted, with a "quote" and C:\\path', None),
    ("description: 'Trailing comment allowed' # note", "Trailing comment allowed", None),
    ("description: Build JUCE plugins with CMake: lifecycle, APVTS", None, "': '"),
    ("description: Covers delay and #hash but also tone # truncated here", None, "' #'"),
    ("description: Ends with a colon:", None, "': '"),
    ("description: - starts like a list item", None, "cannot start with '-'"),
    ("description: *alias-looking start", None, "cannot start with '*'"),
    ("description: 'unterminated", None, "unterminated"),
    ('description: "bad escape \\q"', None, "invalid escape"),
    ("description: 'closed' and more", None, "after the closing quote"),
    ("description: >\n  folded text", None, "block scalars"),
    ("description: first line\n  continued line", None, "multi-line"),
    ("name: x", None, "missing"),
]


def self_test() -> list[str]:
    """Description-parser and cross-skill link fixtures. Explicit checks, not assert, so it also runs under python -O."""
    import shutil
    import tempfile
    failures = []
    link = ("skills/a/SKILL.md", "skills/b/SKILL.md")
    for current, baseline, fragment in [({link}, {link}, None), (set(), set(), None),
                                        ({link}, set(), "new cross-skill relative link"),
                                        (set(), {link}, "no longer exists")]:
        got = link_problems(current, baseline)
        if (fragment is None and got) or (fragment is not None and not any(fragment in p for p in got)):
            failures.append(f"link_problems({current}, {baseline}): expected {fragment!r}, got {got}")
    tmp = Path(tempfile.mkdtemp(prefix="validate-links-"))
    try:
        for rel, text in {"skills/a/SKILL.md": "[b](../b/SKILL.md) [own](references/x.md) [web](https://example.com)",
                          "skills/a/references/x.md": "[y](../../b/references/y.md#part) [x](x.md)\n```\n[code](../../b/SKILL.md)\n```",
                          "skills/b/SKILL.md": "", "skills/b/references/y.md": ""}.items():
            (tmp / rel).parent.mkdir(parents=True, exist_ok=True)
            (tmp / rel).write_text(text, encoding="utf-8")
        got = cross_skill_links(tmp / "skills", tmp)
        want = {("skills/a/SKILL.md", "skills/b/SKILL.md"), ("skills/a/references/x.md", "skills/b/references/y.md")}
        if got != want:
            failures.append(f"cross_skill_links: expected {sorted(want)}, got {sorted(got)}")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    for text, want, error in DESCRIPTION_FIXTURES:
        got, why = frontmatter_description(text)
        if want is not None and (got != want or why is not None):
            failures.append(f"{text!r}: expected {want!r}, got {got!r} ({why})")
        if want is None and (got is not None or why is None or error not in why):
            failures.append(f"{text!r}: expected an error containing {error!r}, got {got!r} ({why})")
    return failures


def check_frontmatter(skill: Path, problems: list[str]) -> None:
    text = (skill / "SKILL.md").read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        problems.append(f"{skill.name}/SKILL.md: missing YAML frontmatter")
        return
    fields = dict(re.findall(r"^([a-z_]+):\s*(.*)$", m.group(1), re.M))
    if fields.get("name") != skill.name or not re.fullmatch(r"[a-z0-9-]+", fields.get("name", "")):
        problems.append(f"{skill.name}/SKILL.md: name {fields.get('name')!r} must equal the directory name")
    desc, why = frontmatter_description(m.group(1))
    if why:
        problems.append(f"{skill.name}/SKILL.md: description does not parse as one complete YAML string: {why}")
    elif not desc.strip():
        problems.append(f"{skill.name}/SKILL.md: empty description")
    elif len(desc) > 1024:
        problems.append(f"{skill.name}/SKILL.md: description is {len(desc)} characters (max 1024)")


def check_agent_yaml(skill: Path, problems: list[str]) -> None:
    path = skill / "agents" / "openai.yaml"
    if not path.is_file():
        problems.append(f"{skill.name}: agents/openai.yaml missing")
        return
    text = path.read_text(encoding="utf-8")
    if not re.search(r"^interface:\s*$", text, re.M):
        problems.append(f"{skill.name}/agents/openai.yaml: no top-level 'interface:' mapping")
    for key in ("display_name", "short_description", "default_prompt"):
        m = re.search(rf'^\s+{key}:\s*"(.+)"\s*$', text, re.M)
        if not m:
            problems.append(f"{skill.name}/agents/openai.yaml: {key} missing or not a quoted string")
        elif key == "default_prompt" and f"${skill.name}" not in m.group(1):
            problems.append(f"{skill.name}/agents/openai.yaml: default_prompt does not mention ${skill.name}")


def code_regions(path: Path) -> list[str]:
    text = path.read_text(encoding="utf-8", errors="replace")
    if path.suffix == ".md":
        return re.findall(r"```.*?```", text, flags=re.S)
    return [text] if path.suffix in MODEL_FILES else []


def check_leaks(problems: list[str]) -> None:
    for path in [ROOT / "README.md", *sorted(p for d in (SKILLS, RFCS, OPERATIONAL) for p in d.rglob("*") if p.is_file())]:
        if path.suffix in {".png", ".jpg", ".jpeg", ".glb", ".blend", ".ico"}:
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for n, line in enumerate(text.split("\n"), 1):
            if PATH_LEAK.search(line):
                problems.append(f"absolute or project path in {path.relative_to(ROOT)}:{n}")
        for region in code_regions(path):
            if VENDOR_MARKERS.search(region):
                problems.append(f"licence marker inside code/model text in {path.relative_to(ROOT)}")
            lines = region.split("\n")
            for i, line in enumerate(lines):
                if re.match(r"\s*\.subckt\b", line, re.I):
                    end = next((j for j in range(i, len(lines)) if re.match(r"\s*\.ends\b", lines[j], re.I)), len(lines))
                    if end - i > MAX_SUBCKT_LINES:
                        problems.append(f"large .subckt ({end - i} lines) in {path.relative_to(ROOT)}: vendor model text?")
                if re.match(r"\s*\.model\b", line, re.I) and line.count("=") > MAX_MODEL_PARAMS:
                    problems.append(f"large .model card in {path.relative_to(ROOT)}: vendor model text?")


def cross_skill_links(skills: Path, root: Path) -> set[tuple[str, str]]:
    """(source file, target path) for every relative Markdown link from one skill into another, anchors ignored."""
    skills, root = skills.resolve(), root.resolve()
    pairs = set()
    for md in sorted(skills.rglob("*.md")):
        own = md.relative_to(skills).parts[0]
        text = re.sub(r"```.*?```", "", md.read_text(encoding="utf-8"), flags=re.S)
        for m in re.finditer(r"\]\(([^)\s]+)\)", text):
            path = m.group(1).partition("#")[0]
            if not path or m.group(1).startswith(("http://", "https://", "mailto:")):
                continue
            target = (md.parent / path).resolve()
            try:
                other = target.relative_to(skills).parts[0]
            except ValueError:
                continue
            if other != own:
                pairs.add((md.relative_to(root).as_posix(), target.relative_to(root).as_posix()))
    return pairs


def link_problems(current: set[tuple[str, str]], baseline: set[tuple[str, str]]) -> list[str]:
    out = [f"new cross-skill relative link {s} -> {t}: name the other skill instead of linking into it"
           for s, t in sorted(current - baseline)]
    out += [f"{LINK_BASELINE.relative_to(ROOT)} lists {s} -> {t}, which no longer exists: remove the entry"
            for s, t in sorted(baseline - current)]
    return out


def check_cross_skill_links(problems: list[str]) -> int:
    try:
        data = json.loads(LINK_BASELINE.read_text(encoding="utf-8"))
        if data.get("kind") != "link-baseline" or data.get("version") != 1:
            raise ValueError("expected kind 'link-baseline', version 1")
        baseline = {tuple(pair) for pair in data["links"]}
    except (OSError, ValueError, KeyError, TypeError) as e:
        problems.append(f"{LINK_BASELINE.relative_to(ROOT)}: cannot be read: {e}")
        return 0
    current = cross_skill_links(SKILLS, ROOT)
    problems.extend(link_problems(current, baseline))
    return len(current)


def load_script(path: Path):
    spec = importlib.util.spec_from_file_location(path.stem, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def check_operational(problems: list[str], skills: list[Path]) -> int:
    sync, records = (load_script(p) for p in REPO_SCRIPTS)
    structural, drift, _ = sync.plan(ROOT)
    problems.extend(f"operational copies: {p}" for p in structural + drift)
    try:
        formats = records.load_formats()
    except (OSError, ValueError) as e:
        problems.append(f"operational formats: {e}")
        return 0
    checker = records.Checker(formats, known_skills={s.name for s in skills})
    examples = sorted(p for p in (OPERATIONAL / "examples").glob("*") if p.is_file())
    for path in examples:
        problems.extend(checker.check_text(path.read_text(encoding="utf-8"), str(path.relative_to(ROOT))))
    return len(examples)


def run_self_tests(problems: list[str]) -> list[str]:
    ran = []
    for script in [*sorted(SKILLS.glob("*/scripts/*.py")), *REPO_SCRIPTS]:
        if "--self-test" not in script.read_text(encoding="utf-8", errors="replace"):
            continue
        for flags in ([], ["-O"]):
            run = subprocess.run([sys.executable, *flags, str(script), "--self-test"], capture_output=True, text=True,
                                 timeout=600)
            label = f"{script.relative_to(ROOT)}{' (-O)' if flags else ''}"
            ran.append(label)
            if run.returncode != 0:
                tail = (run.stdout + run.stderr).strip().split("\n")[-5:]
                problems.append(f"self-test failed: {label}: " + " | ".join(tail))
    return ran


def main() -> int:
    if "--self-test" in sys.argv[1:]:
        failures = self_test()
        for f in failures:
            print("FAIL:", f)
        print(f"validator self-test ({len(DESCRIPTION_FIXTURES)} description fixtures, link fixtures): "
              + ("PASS" if not failures else f"{len(failures)} FAILED"))
        return 1 if failures else 0
    problems: list[str] = [f"validator self-test: {f}" for f in self_test()]
    run = subprocess.run([sys.executable, "-O", str(Path(__file__).resolve()), "--self-test"], capture_output=True, text=True, timeout=120)
    if run.returncode != 0:
        problems.append("validator self-test failed under python -O: " + " | ".join((run.stdout + run.stderr).strip().split("\n")[-5:]))
    skills = sorted(p for p in SKILLS.iterdir() if (p / "SKILL.md").is_file())
    for skill in skills:
        check_frontmatter(skill, problems)
        check_agent_yaml(skill, problems)
    links = check_links(problems)
    check_leaks(problems)
    cross = check_cross_skill_links(problems)
    examples = check_operational(problems, skills)
    ran = run_self_tests(problems)
    for p in problems:
        print("FAIL:", p)
    print(f"{len(skills)} skills, {links} relative links ({cross} cross-skill pairs, baselined), {examples} example records, "
          f"{len(ran)} self-test runs: " + ("ALL CHECKS PASSED" if not problems else f"{len(problems)} PROBLEMS"))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
